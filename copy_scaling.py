def analyze_algorithm(name: str, n_qubits: int, rho_ideal: np.ndarray,
                      noise_configs: List[Dict]) -> List[Dict]:
    """Analyze copy requirements for one algorithm under various noise levels."""
    d = 2**n_qubits
    energies = np.arange(d, dtype=float)
    results = []

    for noise in noise_configs:
        rho_noisy = rho_ideal.copy()
        if noise.get('dephasing', 0) > 0:
            rho_noisy = apply_dephasing(rho_noisy, noise['dephasing'])
        if noise.get('depol', 0) > 0:
            rho_noisy = apply_depolarizing(rho_noisy, noise['depol'])
        if noise.get('amp_damp', 0) > 0:
            rho_noisy = apply_amplitude_damping(rho_noisy, noise['amp_damp'])

        rho_noisy = (rho_noisy + rho_noisy.conj().T) / 2
        rho_noisy /= np.trace(rho_noisy)

        for k in [1, 3, 5, 10]:
            req = compute_full_copy_requirements(
                d, rho_noisy, rho_ideal, energies, k=k
            )
            req['algorithm'] = name
            req['noise_name'] = noise['name']
            req['noise_params'] = noise
            results.append(req)

    return results


def make_ideal_state(n_qubits: int, state_type: str = 'plus') -> np.ndarray:
    """Create ideal state for analysis."""
    d = 2**n_qubits
    if state_type == 'plus':
        psi = np.ones(d, dtype=complex) / np.sqrt(d)
    elif state_type == 'ghz':
        psi = np.zeros(d, dtype=complex)
        psi[0] = 1.0 / np.sqrt(2)
        psi[-1] = 1.0 / np.sqrt(2)
    elif state_type == 'random':
        psi = np.random.randn(d) + 1j * np.random.randn(d)
        psi /= np.linalg.norm(psi)
    else:
        psi = np.ones(d, dtype=complex) / np.sqrt(d)
    return np.outer(psi, psi.conj())


