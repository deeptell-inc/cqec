def count_nonzero_offdiag_pairs(rho: np.ndarray, tol: float = 1e-15) -> int:
    """Count number of distinct off-diagonal pairs (i,j) with i<j and |ρ_{ij}| > tol.
    This determines N (number of 2-level catalysts needed) for the target state.
    """
    d = rho.shape[0]
    count = 0
    for i in range(d):
        for j in range(i + 1, d):
            if abs(rho[i, j]) > tol:
                count += 1
    return count


def count_distinct_modes(rho: np.ndarray, energies: np.ndarray, tol: float = 1e-10) -> int:
    """Count distinct energy gaps Δ_{ij} with nonzero coherence.
    This is |D(ρ)|, the set of modes of asymmetry.
    """
    modes = modes_of_asymmetry(rho, energies, tol)
    return len(modes)


def min_nonzero_coherence(rho: np.ndarray, tol: float = 1e-15) -> float:
    """Find minimum nonzero off-diagonal element magnitude."""
    d = rho.shape[0]
    min_val = float('inf')
    for i in range(d):
        for j in range(d):
            if i != j and abs(rho[i, j]) > tol:
                min_val = min(min_val, abs(rho[i, j]))
    return min_val if min_val < float('inf') else 0.0


def compute_N_catalysts(rho_target: np.ndarray, energies: np.ndarray) -> int:
    """Compute N: number of 2-level catalytic systems needed.

    From Lemma S.12 (Theorem 2 in Ref [45]):
    For any two quantum states ξ and ρ', and for any accuracy ε > 0,
    there exists a set of two-level catalytic systems C_1,...,C_N
    with full-rank qubit mixed states c_1,...,c_N and a covariant operation Λ.

    N is determined by the number of distinct coherent modes in ρ'.
    Specifically, each mode Δ ∈ D(ρ') requires at least one 2-level catalyst
    with matching energy gap, but modes can share catalysts if they
    are integer multiples.

    Conservative bound: N = |D(ρ')| (number of distinct modes)
    Tight bound: N = rank of D(ρ') as a Z-module
    """
    modes = modes_of_asymmetry(rho_target, energies)
    if not modes:
        return 0

    # Find the rank of the Z-module generated by the modes
    # This equals the number of rationally independent generators
    mode_list = sorted(modes)

    # Simple approach: count rationally independent modes
    independent = []
    for m in mode_list:
        if abs(m) < 1e-10:
            continue
        is_dependent = False
        for ind in independent:
            if abs(ind) < 1e-10:
                continue
            ratio = m / ind
            # Check if ratio is a rational number p/q with small p,q
            for q in range(1, 20):
                p = round(ratio * q)
                if abs(ratio * q - p) < 1e-8:
                    is_dependent = True
                    break
            if is_dependent:
                break
        if not is_dependent:
            independent.append(m)

    return max(len(independent), 1)


def compute_mu_per_catalyst(rho_source: np.ndarray, energies: np.ndarray,
                             noise_strength: float = 0.0) -> float:
    """Compute μ_i: copies of ρ needed to prepare one 2-level catalyst.

    From the proof chain (Lemma S.16 → S.17):

    Step 1 (Lemma S.16): ρ^{⊗m} → weakly coherent qubit state η
      - Requires: D(η) ⊆ D(ρ)
      - Copy count m: depends on the protocol in Ref [45, Lemma 11]
      - Scaling: m ~ O(1/|ρ_{ij}|²) for the matching mode
        (need to extract coherence from weak off-diagonal elements)

    Step 2 (Ref [53], Cirac-Ekert-Macchiavello 1999):
      η^{⊗m'} → one copy of |+><+| (maximally coherent qubit)
      - m' ~ 1/C_l1(η)² (inverse square of L1 coherence of η)
      - But η already has nonzero coherence, so m' = O(1)

    Step 3 (exact preparation via Lemma S.14):
      |+><+|^{⊗k'} → c_i (target full-rank qubit catalyst)
      - k' = O(1) since |+> is maximally coherent among qubits
      - The coherence cost 1/R(|+><+| → c_i) = QFI(c_i)/QFI(|+><+|) ≤ 1

    Combined: μ_i = m · m' · k'

    For practical computation:
      If ρ has been affected by dephasing with parameter γ:
        |ρ_{ij}| ~ |ρ^{ideal}_{ij}| · exp(-γ)
        m ~ 1/exp(-2γ) = exp(2γ)

      If ρ has been affected by depolarizing noise p:
        |ρ_{ij}| ~ (1-p)|ρ^{ideal}_{ij}|
        m ~ 1/(1-p)²
    """
    d = rho_source.shape[0]

    # Find minimum nonzero coherence (bottleneck mode)
    min_coh = min_nonzero_coherence(rho_source)

    if min_coh <= 0:
        return float('inf')  # Cannot prepare catalyst

    # Step 1: copies to extract one weakly coherent qubit
    # From Ref [45], Lemma 11: The protocol uses O(1/|ρ_{ij}|²) copies
    # to produce a state with coherence on the matching mode
    m = ceil(1.0 / (min_coh ** 2))

    # Step 2: copies to amplify weak coherence to max coherence
    # From Cirac-Ekert-Macchiavello (PRL 82, 4344, 1999):
    # Need ~1/C² copies of a state with coherence C to get |+>
    # But after Step 1, we have coherence ~min_coh * sqrt(m) ~ 1
    # so m' ~ O(1)
    m_prime = 1  # Constant factor

    # Step 3: convert |+> to target catalyst
    # Since |+> is maximally coherent, k' = O(1)
    k_prime = 1

    # Total copies per catalyst
    mu_i = m * m_prime * k_prime

    return mu_i


def compute_full_copy_requirements(
    d: int,
    rho_source: np.ndarray,
    rho_target: np.ndarray,
    energies: np.ndarray,
    k: int = 1,
    epsilon: float = 0.01,
) -> Dict:
    """Compute full copy requirements for ICEC protocol.

    Args:
        d: Hilbert space dimension (2^n_qubits)
        rho_source: noisy source state
        rho_target: ideal target state
        energies: energy eigenvalues
        k: amplification rounds (controls rate)
        epsilon: target accuracy

    Returns:
        Dictionary with all scaling parameters
    """
    # N: number of 2-level catalysts
    N = compute_N_catalysts(rho_target, energies)

    # μ_i per catalyst
    mu_per = compute_mu_per_catalyst(rho_source, energies)

    # Total μ = N · μ_per (conservative: each catalyst costs the same)
    mu_total = N * mu_per

    # Input copies: n = μ · N^k
    n_input = mu_total * (N ** k) if N > 0 else mu_total

    # Output copies: m = (k+1) · N^k
    m_output = (k + 1) * (N ** k) if N > 0 else (k + 1)

    # Rate
    rate = m_output / n_input if n_input > 0 else 0

    # Catalyst dimension (from Eq. 34 of Prop S.23)
    # c = (1/n) Σ_{k=1}^n ρ^{⊗(k-1)} ⊗ τ_{n-k} ⊗ |k><k|_R
    # dim(c) = d^{n-1} · d · n (system copies × remainder × register)
    # In practice, use the asymptotic n from the protocol
    n_for_catalyst = max(int(mu_total), 2)
    catalyst_dim_log2 = (n_for_catalyst - 1) * log2(d) + log2(d) + log2(n_for_catalyst)

    # Total qubits for the full protocol
    # System: n_qubits = log2(d)
    # Catalysts: N qubits (each 2-level)
    # Ancillas for covariant operation: O(N) qubits
    n_system_qubits = int(ceil(log2(d)))
    n_catalyst_qubits = N  # Each catalyst is 2-level (1 qubit)
    n_ancilla_qubits = N   # Ancillas for EC gates
    total_qubits = n_system_qubits + n_catalyst_qubits + n_ancilla_qubits

    # Coherence metrics
    coh_source = coherence_l1(rho_source, energies)
    coh_target = coherence_l1(rho_target, energies)
    min_coh = min_nonzero_coherence(rho_source)

    return {
        'dimension': d,
        'n_system_qubits': n_system_qubits,
        'N_catalysts': N,
        'mu_per_catalyst': mu_per,
        'mu_total': mu_total,
        'k_rounds': k,
        'n_input_copies': n_input,
        'm_output_copies': m_output,
        'rate': rate,
        'total_operational_qubits': total_qubits,
        'n_catalyst_qubits': n_catalyst_qubits,
        'catalyst_dim_log2': catalyst_dim_log2,
        'coh_source_l1': coh_source,
        'coh_target_l1': coh_target,
        'min_nonzero_coherence': min_coh,
    }


