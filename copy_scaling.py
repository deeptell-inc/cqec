def apply_dephasing(rho, gamma):
    d = rho.shape[0]
    result = rho.copy()
    for i in range(d):
        for j in range(d):
            if i != j:
                result[i, j] *= np.exp(-gamma)
    return result

def apply_depolarizing(rho, p):
    d = rho.shape[0]
    return (1 - p) * rho + p * np.eye(d, dtype=complex) / d

def apply_amplitude_damping(rho, gamma):
    d = rho.shape[0]
    result = rho.copy()
    for i in range(d):
        for j in range(d):
            if i != j:
                result[i, j] *= np.sqrt(1 - gamma)
    # Shift populations
    result[0, 0] += gamma * (1 - result[0, 0].real)
    for i in range(1, d):
        result[i, i] *= (1 - gamma)
    result /= np.trace(result)
    return result


